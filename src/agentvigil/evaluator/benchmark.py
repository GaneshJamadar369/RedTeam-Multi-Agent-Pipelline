import random
from typing import List, Dict, Tuple
from ..core.data_models import Task, Seed
import logging

class BenchmarkEvaluator:
    """
    Handles splitting tasks into fuzzing and test sets, and evaluating 
    transferability across different models as described in the AgentVigil paper.
    """
    
    @staticmethod
    def split_tasks(task_suites: Dict[str, List[Task]], test_ratio: float = 0.5) -> Tuple[Dict[str, List[Task]], Dict[str, List[Task]]]:
        """
        Splits the given task suites into a fuzzing set and a test set.
        """
        fuzzing_set = {}
        test_set = {}
        
        for suite_name, tasks in task_suites.items():
            shuffled_tasks = tasks.copy()
            random.shuffle(shuffled_tasks)
            
            split_idx = int(len(shuffled_tasks) * (1 - test_ratio))
            fuzzing_set[suite_name] = shuffled_tasks[:split_idx]
            test_set[suite_name] = shuffled_tasks[split_idx:]
            
            logging.info(f"Suite '{suite_name}': {len(fuzzing_set[suite_name])} fuzzing tasks, {len(test_set[suite_name])} test tasks.")
            
        return fuzzing_set, test_set

    @staticmethod
    def evaluate_transferability(best_seeds: List[Seed], test_tasks: Dict[str, List[Task]], runner_factory: callable, models: List[str]):
        """
        Evaluates how well the generated adversarial prompts transfer to different LLM backbones.
        
        Args:
            best_seeds: The top seeds generated by the fuzzing loop.
            test_tasks: The held-out test task set.
            runner_factory: A function that takes a model name and returns an AgentRunner instance.
            models: List of model names to test against (e.g., ['o3-mini', 'gpt-4o', 'claude-3.5-sonnet']).
        """
        results = {}
        for model in models:
            logging.info(f"Evaluating transferability against model: {model}")
            runner = runner_factory(model)
            
            total_tasks = sum(len(tasks) for tasks in test_tasks.values())
            success_count = 0
            
            for suite_name, tasks in test_tasks.items():
                for task in tasks:
                    # Test each task with all top seeds. If any seed works, it's considered a success for this task.
                    # This simulates taking the union of adversarial prompts.
                    task_compromised = False
                    for seed in best_seeds:
                        if runner.run(seed, task):
                            task_compromised = True
                            break
                    if task_compromised:
                        success_count += 1
                        
            success_rate = success_count / total_tasks if total_tasks > 0 else 0
            results[model] = success_rate
            logging.info(f"Transferability Success Rate on {model}: {success_rate:.2f}")
            
        return results
